async function seedStateHeroSlides() {
  const client = new MongoClient(MONGODB_URI);
  try {
    await client.connect();
    const db = client.db(MONGODB_DB);
    const collection = db.collection("state_hero_slides");

    console.log("Connected to MongoDB. Seeding state and city hero slides...");

    for (const slide of sampleSlides) {
      await collection.updateOne(
        {
          stateName: slide.stateName,
          cityName: slide.cityName || "",
          destinationName: slide.destinationName,
        },
        {
          $set: {
            ...slide,
            updatedAt: new Date(),
          },
          $setOnInsert: {
            createdAt: new Date(),
          },
        },
        { upsert: true }
      );
    }

    const totalCount = await collection.countDocuments({});
    console.log(`✓ Seeded slides successfully. Total slides in collection: ${totalCount}`);
  } finally {
    await client.close();
  }
}

seedStateHeroSlides().catch((err) => {
  console.error("Failed to seed hero slides:", err);
  process.exit(1);
});
